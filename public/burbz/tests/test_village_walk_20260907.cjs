const assert=require('node:assert/strict');
const C=require('../village_walk_core.js');
const square=[{x:-1,z:-1},{x:1,z:-1},{x:1,z:1},{x:-1,z:1}];
const w=C.createWorld({radius:12,polygons:[square]});
assert(!w.allowed(0,0));assert(!w.allowed(1.1,0));assert(w.allowed(1.5,0));
let p={x:0,z:4,y:0,yaw:0,pitch:0};
for(let i=0;i<600;i++)C.move(p,{forward:1,side:0},1/60,w);
assert(p.z>=1+C.RADIUS&&p.z<1.4,'continuous motion stops at wall');
for(let i=0;i<60;i++)C.move(p,{forward:1,side:1},1/60,w);
assert(p.x>1&&w.allowed(p.x,p.z),'diagonal motion slides around the wall');
p={x:0,z:4,y:0,yaw:0,pitch:0};C.move(p,{forward:1},1000,w);assert(p.z>3.8,'resume cannot teleport');
const a={x:0,z:4,yaw:0},b={...a};C.move(a,{forward:1},.05,w);C.move(b,{forward:1,side:1},.05,w);
assert(Math.abs(Math.hypot(a.x,a.z-4)-Math.hypot(b.x,b.z-4))<1e-8,'no diagonal speed boost');
for(let i=0;i<1000;i++)C.move(p,{forward:-1},.05,w);assert(Math.hypot(p.x,p.z)<=12-C.RADIUS,'meadow boundary');
assert(w.allowed(w.spawn({x:0,z:0}).x,w.spawn({x:0,z:0}).z),'spawn escapes building');
const r=C.createWorld({river:{x:0,z:0,ux:1,uz:0,width:3.4}});
assert(r.allowed(0,0));assert(!r.allowed(0,1));assert(r.allowed(4,1));assert(r.height(0,0)>.7,'bridge deck is above water');
assert(r.height(3,0)>0&&r.height(4,0)===0,'bridge ramps meet ground');
const slope=C.createWorld({heightAt:(x,z)=>x/10});p={x:4,z:4,yaw:0,pitch:0};C.move(p,{side:1},.05,slope);assert.equal(p.y,p.x/10);
C.look(p,20,100000);assert.equal(p.pitch,-1.1);C.look(p,0,-100000);assert.equal(p.pitch,1.1);
assert.equal(C.quality(1.5,1.5,Array(60).fill(24)).dpr,1.35);
assert.equal(C.quality(.65,1.5,Array(60).fill(100)).dpr,.65);
assert.equal(C.quality(1,1.5,Array(60).fill(16.6),3).dpr,1.1);
console.log('Village walk: collision, slide, boundary, spawn, bridge, terrain, input and resolution checks passed.');
