'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const css = fs.readFileSync(path.join(root, 'scan_home.css'), 'utf8');
const selector = '#screen-scan.progressive-home #scanHomeActions .home-action[data-home-action="next-quest"]:not(:disabled)';
const start = css.indexOf('/* Current quest:');
assert(start >= 0, 'Current quest has its own scoped pulse styling');
const pulse = css.slice(start);
assert(pulse.includes(selector), 'Pulse targets the actual enabled current-quest button, not Goal');
assert.match(pulse, /animation:\s*home-current-quest-pulse 4s ease-in-out infinite/);
assert.match(pulse, /@keyframes home-current-quest-pulse/);
assert.match(pulse, /0%,\s*100%\s*\{/);
assert.match(pulse, /50%\s*\{/);
assert.match(pulse, /inset 0 0 0 1px rgba\(220,\s*72,\s*64,/);
assert.match(pulse, /@media\s*\(prefers-reduced-motion:\s*reduce\)[\s\S]*animation:\s*none/);
assert(!/(?:^|[;{])\s*(?:transform|opacity|color|background|padding|margin|width|height|border-width)\s*:/.test(pulse), 'Only glow changes: no movement, fading text, or layout changes');
assert.equal((pulse.match(/data-home-action=/g) || []).length, 2, 'Only normal and reduced-motion quest selectors');
const ui = fs.readFileSync(path.join(root, 'scan_home.js'), 'utf8');
assert(ui.includes("m.actions.filter(a=>a.id==='next-quest').slice(0,1)"), 'One generic current quest');
assert(ui.includes('data-home-action="${escape(a.id)}"'), 'Existing action identity remains');
assert(ui.includes('options.open(target)'), 'Existing delegated destination remains');
console.log('PASS current-quest-only slow red glow, stationary readable content, reduced-motion static highlight, unchanged generic action routing');
