#!/usr/bin/env node

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const manifestPath = path.join(root, 'data', 'burbz-art-recovery-manifest-20260720.json');
const outputPath = path.join(root, 'public', 'burbz', 'generated_bird_art_20260720.js');

const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const generated = manifest.birds.filter(bird => bird.status === 'generated');
const art = {};

for (const bird of generated) {
  if (!bird.species || !bird.targetRelativePath || !bird.targetUrl) {
    throw new Error(`Incomplete generated-art record at manifest index ${bird.index}`);
  }
  if (Object.prototype.hasOwnProperty.call(art, bird.species)) {
    throw new Error(`Duplicate generated-art species: ${bird.species}`);
  }

  const assetPath = path.join(root, ...bird.targetRelativePath.split('/'));
  const payload = fs.readFileSync(assetPath);
  const sha256 = crypto.createHash('sha256').update(payload).digest('hex');

  if (bird.outputBytes !== payload.length) {
    throw new Error(`Size mismatch for ${bird.species}: ${payload.length} != ${bird.outputBytes}`);
  }
  if (bird.outputSha256 !== sha256) {
    throw new Error(`SHA-256 mismatch for ${bird.species}: ${sha256} != ${bird.outputSha256}`);
  }

  art[bird.species] = bird.targetUrl;
}

const source = `/* Generated by scripts/build-burbz-generated-art-map.js. Do not edit by hand. */
globalThis.BURBZ_GENERATED_BIRD_ART_20260720 = Object.freeze(${JSON.stringify(art, null, 2)});
`;

fs.writeFileSync(outputPath, source, 'utf8');
console.log(`Verified and mapped ${generated.length} recovered portraits in ${path.relative(root, outputPath)}`);
